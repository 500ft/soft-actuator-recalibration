function render_tables(root, outRoot)
%RENDER_TABLES Write the headline result tables as LaTeX tabular fragments.
%   docs/tables/policy_table.tex  from data/sim/summary/policy_comparison.csv
%   docs/tables/gate0_table.tex   from data/gate0/gate0_results.json
%   Booktabs rules and siunitx units. Every number is read from the committed
%   file and rounded as in the Markdown tables; nothing is typed by hand.
%   Typeset them with the figure kit's table2img.py (see figures/matlab/README.md).

if nargin < 1 || isempty(root)
    root = fileparts(fileparts(fileparts(mfilename('fullpath'))));
end
if nargin < 2 || isempty(outRoot), outRoot = root; end
d = fullfile(outRoot, 'docs', 'tables');
if ~isfolder(d), mkdir(d); end

% ---- policy table -----------------------------------------------------------
T = readtable(fullfile(root, 'data/sim/summary/policy_comparison.csv'), 'TextType', 'string', ...
    'VariableNamingRule', 'preserve', 'Delimiter', ',');
rows = strings(height(T), 1);
for i = 1:height(T)
    lab = replace(T.label(i), "τ", "$\tau$");
    rows(i) = sprintf('%s & %.3f & %.1f \\\\', lab, T.mean_pose_rmse_mm(i), T.recalibrations_per_actuator(i));
end
L = [
"% Generated by figures/matlab/render_tables.m from data/sim/summary/policy_comparison.csv; do not edit by hand."
"\begin{tabular}{@{}l S[table-format=1.3] S[table-format=1.1]@{}}"
"\toprule"
"Policy & {Mean pose error, RMSE (\unit{\milli\metre})} & {Calibrations per actuator} \\"
"\midrule"
rows
"\bottomrule"
"\end{tabular}"
];
writelines(L, fullfile(d, 'policy_table.tex'));

% ---- Gate 0 table -----------------------------------------------------------
R = sar_json(fullfile(root, 'data/gate0/gate0_results.json'));
hm = R.headline_metric; sf = R.most_sensitive_frequency; rb = R.robustness;
f = R.params.f_actuation_hz;
assert(rb.all_same_sign_positive, 'expected every randomized set to have positive sign');
g = {
    sprintf('Change in static (DC) cross-talk, $C_1$ $1{\\times} \\to 2{\\times}$ & \\num{%.4f} & \\unit{\\percent}', ...
        100 * R.dc_independence.relative_change)
    sprintf('Rank correlation of %g Hz cross-talk with $C_1$ (Spearman $\\rho$, $p \\approx 0$) & \\num{%+.3f} & \\textendash', ...
        f, hm.spearman_rho)
    sprintf('Rise in %g Hz cross-talk over the $C_1$ sweep & \\num{%+.0f} & \\unit{\\percent}', f, 100 * hm.relative_drift)
    sprintf('Most fatigue-sensitive frequency, by neighbour pressure $|H_{21}|$ & \\num{%.1f} & \\unit{\\hertz}', sf.freq_hz)
    sprintf('Usable cross-talk band & \\numrange{%.1f}{%.1f} & \\unit{\\hertz}', sf.usable_band_hz(1), sf.usable_band_hz(2))
    sprintf('Randomized $R$/$C$/$P$ sets with monotone cross-talk, all positive sign ($n = %d$) & \\num{%.0f} & \\unit{\\percent}', ...
        rb.n, 100 * rb.frac_monotone)
    sprintf('Randomized $R$/$C$/$P$ sets with more than \\qty{10}{\\percent} drift ($n = %d$) & \\num{%.0f} & \\unit{\\percent}', ...
        rb.n, 100 * rb.frac_pass)
    };
L = [
"% Generated by figures/matlab/render_tables.m from data/gate0/gate0_results.json; do not edit by hand."
"\sisetup{print-implicit-plus=false, retain-explicit-plus=true, range-phrase={\textendash}}"
"\begin{tabular}{@{}l r l@{}}"
"\toprule"
"Result & {Value} & Unit \\"
"\midrule"
string(g) + " \\"
"\bottomrule"
"\end{tabular}"
];
writelines(L, fullfile(d, 'gate0_table.tex'));
fprintf('OK   docs/tables/policy_table.tex\nOK   docs/tables/gate0_table.tex\n');
end
