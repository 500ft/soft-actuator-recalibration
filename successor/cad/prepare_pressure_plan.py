"""Render the owner-required draft P1-P7 plan from its actual design inputs."""
import argparse
import json
from pathlib import Path

import oracle

HERE=Path(__file__).resolve().parent


def main():
    p=argparse.ArgumentParser();p.add_argument('--desktop',type=Path,required=True);args=p.parse_args()
    g=json.loads((HERE/'geometry.json').read_text());plan=json.loads((HERE/'pressure_plan_inputs.json').read_text())
    run=args.desktop/'04_ANALYSIS/successor-concepts';actual=json.loads((run/'result.json').read_text())
    screening=oracle.screening(g,actual['adjuster_length_mm']);cases=screening['force_cases']
    working=oracle.v(g,'specimen','working_pressure');proof=oracle.v(g,'specimen','proof_pressure')
    if abs(proof-working*plan['proof_to_working_ratio'])>1e-8:raise ValueError('Proof/working ratio differs from the owner plan; review before rendering')
    force=max(c['blocked_force_N'] for c in cases);pullout=force*plan['pullout_factor_of_blocked_force'];frame=max(c['proof_pressure_force_N'] for c in cases)
    rated=oracle.v(g,'cell','rated_force')
    result={'accepted':None,'status':plan['status'],'working_pressure_kPa_gauge':working,'proof_pressure_kPa_gauge':proof,
            'blocked_force_envelope_N':force,'minimum_pullout_force_N':pullout,'proposed_cell_rated_N':rated,'frame_design_case_N':frame,
            'existing_frame_and_cell_qualify_for_pullout':False,'reason':'Required pull-out load exceeds the proposed cell rating and frame design case; no separate pull-out machine/fixture has been identified or qualified.',
            'leak_duration_s':plan['leak_duration_s'],'leak_decay_limit_kPa':plan['leak_pressure_decay_limit_kPa'],
            'detail_plan_gate_closed':False,'physical_work_authorized':False,'pressure_rating_established':False}
    (run/'pressure_plan_review.json').write_text(json.dumps(result,indent=2)+'\n')
    text=f'''# Pressure qualification plan P1-P7

Status: DRAFT / HOLD. This is the written plan required by the CAD handoff.
Decision 0004 authorizes no fabrication, hardware test or pressurization.
Owner O12/O13/O14b/O15, the missing selections below and the institutional
review remain open. Writing this file does not close the pressure-detail gate.

This file is generated by `cad/prepare_pressure_plan.py`. Pressure values live
in `cad/geometry.json`; the other prescribed criteria live in
`cad/pressure_plan_inputs.json`. Calculated loads and holds are in the executed
`pressure_plan_review.json`, delivered with the concept results.

| Item | Method and acceptance required by the owner | Evidence still needed |
| --- | --- | --- |
| P1 | Every pressurized part has a design MAWP of {working:g} kPa gauge. Record gauge/absolute convention on each drawing and test record. | Actual component identities, temperature range, ratings and reviewer acceptance. A CAD value is not a pressure rating. |
| P2 | Relief downstream of the regulator, set no higher than {plan['relief_set_max_kPa_gauge']:g} kPa gauge and sized for the regulator's full flow. | Regulator/relief identities, full-flow data, discharge routing and setting verification. No device is selected or bought. |
| P3 | Machined 6061-T6 pressure fittings/chamber; standard AS568 or ISO 3601 O-ring glands. Commercial tubing and fittings rated at least {plan['commercial_component_min_rating_kPa']:g} kPa at the actual test temperature. The bladder is the intended failure specimen. | O12 materials; O13 interfaces; O14b sensor audit; exact seal elastomer, standard size/groove and supplier rating documents. Helical threads, final tap drills and seal grooves remain outside the concept model. |
| P4 | Per part type before first use: water-filled hydrostatic proof at {proof:g} kPa gauge, at least {plan['hydrostatic_min_hold_minutes']:g} minutes behind a reviewed shield. Accept only with no leakage and no permanent deformation; inspect critical dimensions before and after. | Approved local procedure, competent supervisor, instrumentation/calibration, stored-energy review, shield/fixture, isolation/vent/drain method and dimensional uncertainty. Pneumatic proof is outside this plan unless stored energy is calculated and the owner separately accepts it. |
| P5 | Separate air leak test at MAWP: pressure decay over a fixed interval against a limit derived from sensor resolution, plus bubble checks at joints. | O14b sensor identity/resolution and a pre-registered time/decay criterion with temperature stabilization. These fields remain null, so P5 is not ready to execute. Hydrostatic proof does not replace this test. |
| P6 | Fitting pull-out at least {plan['pullout_factor_of_blocked_force']:g} times the blocked-force envelope at working pressure, before the pilot. Log fitting failures separately from bladder failures. | A separately qualified load train, load measurement and guarded pull-out method. The proposed operating rig and cell do not qualify for this load by their current design basis. Do not perform P6 on that rig. |
| P7 | Store every executed result next to the successor part's evidence with part number, revision, specimen/lot and procedure revision. | Named owner/reviewer and record of authorization. No pressure or pull-out result exists yet. |

The current concept load model gives a minimum pull-out force of {pullout:.3f} N.
The proposed cell is rated {rated:g} N and the operating frame's design case is
{frame:.3f} N. A different test facility/fixture or a separately reviewed upgrade
is required; the operating-frame CAD has not been silently resized.

## Qualification sequence and record

Before physical work, the owner selects the actual specimen/components and
institutional procedure, identifies the qualified reviewer/test personnel,
closes the sensor and seal selections, reviews the detailed drawings/analysis,
and separately approves fabrication and testing. The reviewer defines the
pressure boundary and test volumes, stored-energy basis, exclusion/shielding,
instrumentation, pressure control/isolation/venting, inspection and stop actions.
No numerical exclusion distance or unverified shielding capacity is invented.

After approved fabrication and inspection, execute the reviewed P4 proof,
separate P5 leak check and separately rated P6 pull-out qualification before the
muscle lifetime pilot. Replace or redesign failed parts under a new revision
and repeat the qualification applicable to the changed part. The operator uses
the approved local procedure rather than this CAD note as an operating SOP.

Each record must identify PN/revision, material/lot, specimen and fitting IDs,
test medium and temperature, gauge convention, pressure or force time history,
instrument IDs/calibration/resolution, duration, pre/post critical dimensions,
leak criterion and result, photos, observed failure mode and reviewer disposition.
Record failures and incomplete tests explicitly; never infer a rating from a
simulation or from the absence of a recorded failure.

## Procedure reference

The owner's requested reference is [Jefferson Lab's Pressure and Vacuum Systems
Safety Supplement, Part 6](https://www.jlab.org/sites/default/files/engdiv/press_syst/JLab%20Pressure%20and%20Vacuum%20Systems%20Supplement.pdf),
PDF pages 71-76, printed Part 6 pages 1-6. It is used as a procedural model for
scope, stored energy, qualified supervision and documentation. The applicable
institutional procedure and reviewer still have to be identified; this document
claims no Jefferson Lab approval, code certification or pressure qualification.
'''
    target=HERE.parent/'docs/pressure_qualification_plan.md';target.parent.mkdir(parents=True,exist_ok=True);target.write_text(text)
    print(json.dumps(result,indent=2))


if __name__=='__main__':main()
